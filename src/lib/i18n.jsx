const DICTS = { en: {}, ru: RU };

const Ctx = createContext({
  lang: DEFAULT,
  setLang: () => {},
  toggle: () => {},
  t: (s) => s,
});

function applyLang(l) {
  if (typeof document === "undefined") return;
  document.documentElement.setAttribute("lang", l);
}

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(DEFAULT);

  useEffect(() => {
    if (typeof window === "undefined") return;
    const l = localStorage.getItem("norvex_lang");
    if (l && LANGS[l]) setLangState(l);
  }, []);

  useEffect(() => {
    applyLang(lang);
  }, [lang]);

  const setLang = useCallback((l) => {
    if (!LANGS[l]) return;
    setLangState(l);
    if (typeof window !== "undefined") localStorage.setItem("norvex_lang", l);
  }, []);

  const toggle = useCallback(() => {
    setLangState((cur) => {
      const next = cur === "ru" ? "en" : "ru";
      if (typeof window !== "undefined") localStorage.setItem("norvex_lang", next);
      return next;
    });
  }, []);

  const t = useCallback(
    (s) => {
      const dict = DICTS[lang] || {};
      return dict[s] != null ? dict[s] : s;
    },
    [lang]
  );

  return <Ctx.Provider value={{ lang, setLang, toggle, t }}>{children}</Ctx.Provider>;
}

export function useLang() {
  return useContext(Ctx);
}
